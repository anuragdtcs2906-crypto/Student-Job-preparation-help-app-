def seed_pronunciation_words():
    """Seed pronunciation words idempotently."""
    from app.models.content import PronunciationWord

    existing_words = {w.word for w in PronunciationWord.query.all()}
    added = 0

    for item in PRONUNCIATION_DATA:
        if item["word"] not in existing_words:
            word = PronunciationWord(**item)
            db.session.add(word)
            added += 1

    db.session.commit()
    print(f"  Pronunciation: {added} new words added (total dataset: {len(PRONUNCIATION_DATA)})")
