def seed_goals():
    """Seed goals, levels, and level configurations."""
    for g_data in GOALS_DATA:
        goal = Goal.query.filter_by(slug=g_data["slug"]).first()
        if not goal:
            goal = Goal(
                slug=g_data["slug"],
                name=g_data["name"],
                description=g_data["description"],
                icon=g_data["icon"],
                display_order=g_data["display_order"],
                target_unit=g_data["target_unit"],
                default_target_quantity=g_data["default_target_quantity"],
            )
            db.session.add(goal)
            db.session.flush()

        for lvl_data in g_data["levels"]:
            level = Level.query.filter_by(goal_id=goal.id, level_number=lvl_data["level_number"]).first()
            if not level:
                level = Level(
                    goal_id=goal.id,
                    level_number=lvl_data["level_number"],
                    title=lvl_data["title"],
                    description=lvl_data["description"],
                    required_mastery_percentage=lvl_data["required_mastery_percentage"],
                    content_focus=lvl_data["content_focus"],
                )
                db.session.add(level)

            cfg_data = lvl_data["config"]
            config = LevelConfiguration.query.filter_by(goal_id=goal.id, assigned_level=lvl_data["level_number"]).first()
            if not config:
                config = LevelConfiguration(
                    goal_id=goal.id,
                    assigned_level=lvl_data["level_number"],
                    min_score_percent=cfg_data["min_score_percent"],
                    max_score_percent=cfg_data["max_score_percent"],
                    criteria_description=cfg_data["criteria_description"],
                    strengths_summary=cfg_data["strengths_summary"],
                    practice_focus=cfg_data["practice_focus"],
                    supportive_message=cfg_data["supportive_message"],
                )
                db.session.add(config)

    db.session.commit()
